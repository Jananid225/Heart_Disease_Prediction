import { test, expect } from '@playwright/test';
import fs from 'fs';

test('Memory-Optimized Workspace Validation Test', async ({ browser }) => {
    let targetUrl = process.env.WEB_URL;

    if (!targetUrl) {
        throw new Error('Run aborted: WEB_URL environment variable is missing.');
    }

    if (!/^https?:\/\//i.test(targetUrl)) {
        targetUrl = `https://${targetUrl}`;
    }

    const context = await browser.newContext();
    const page = await context.newPage();

    try {
        console.log(`Navigating safely to target endpoint: ${targetUrl}`);

        await page.goto(targetUrl, {
            waitUntil: 'networkidle',
            timeout: 30000
        });

        const pageTitle = await page.title();
        console.log(`Page loaded successfully. Title captured: "${pageTitle}"`);

        await expect(page).not.toHaveTitle(/^s*$/);

        // --- HTML REPORT GENERATION (SUCCESS) ---
        const reportHtml = `
            <!DOCTYPE html>
            <html lang="en">
            <head>
                <!-- charset: this report contains multi-byte characters, and without a
                     declaration a browser guesses the encoding - desktop and mobile guess
                     differently, so the heading renders as mojibake on one of them. -->
                <meta charset="utf-8" />
                <!-- viewport: without it a phone lays this out at ~980px and scales down. -->
                <meta name="viewport" content="width=device-width, initial-scale=1" />
                <title>Test Report</title>
                <style>
                    body { font-family: system-ui, sans-serif; padding: 40px; background: #f6f8fa; color: #1f2328; }
                    .card { background: white; padding: 24px; border-radius: 12px; box-shadow: 0 4px 6px -1px rgba(28, 12, 4, 0.10); max-width: 600px; margin: 0 auto; border-top: 4px solid #116329;}
                    /* 40px of padding on a 360px screen spends a fifth of the width on margin. */
                    @media (max-width: 600px) { body { padding: 16px; } .card { padding: 18px; } }
                </style>
            </head>
            <body>
                <div class="card">
                    <h2 style="color: #116329; margin-top: 0;">✅ Run Successful</h2>
                    <p><strong>URL Tested:</strong> ${targetUrl}</p>
                    <p><strong>Page Title:</strong> ${pageTitle}</p>
                    <hr style="border: none; border-top: 1px solid #d1d9e0; margin: 20px 0;" />
                    <p style="font-size: 12px; color: #656c76;">Generated by Orchestrator</p>
                </div>
            </body>
            </html>
        `;
        fs.writeFileSync('run-report.html', reportHtml);

    } catch (error) {
        console.error(`❌ Critical automation failure during runtime: ${error.message}`);
        
        // --- HTML REPORT GENERATION (FAILURE) ---
        const errorHtml = `
            <!DOCTYPE html>
            <html lang="en">
            <head>
                <!-- Same two as the success report above: encoding, then mobile layout. -->
                <meta charset="utf-8" />
                <meta name="viewport" content="width=device-width, initial-scale=1" />
                <title>Test Report</title>
                <style>
                    body { font-family: system-ui, sans-serif; padding: 40px; background: #f6f8fa; color: #1f2328; }
                    .card { background: white; padding: 24px; border-radius: 12px; box-shadow: 0 4px 6px -1px rgba(28, 12, 4, 0.10); max-width: 600px; margin: 0 auto; border-top: 4px solid #a40e26;}
                    pre { background: #1f2328; color: #f6f8fa; padding: 16px; border-radius: 8px; overflow-x: auto; font-size: 13px; }
                    @media (max-width: 600px) { body { padding: 16px; } .card { padding: 18px; } }
                </style>
            </head>
            <body>
                <div class="card">
                    <h2 style="color: #a40e26; margin-top: 0;">❌ Run Failed</h2>
                    <p><strong>URL Tested:</strong> ${targetUrl}</p>
                    <p><strong>Error Details:</strong></p>
                    <pre>${error.message}</pre>
                    <hr style="border: none; border-top: 1px solid #d1d9e0; margin: 20px 0;" />
                    <p style="font-size: 12px; color: #656c76;">Generated by Orchestrator</p>
                </div>
            </body>
            </html>
        `;
        fs.writeFileSync('run-report.html', errorHtml);

        throw error;
    } finally {
        await page.close();
        await context.close();
        console.log('Browser context safely reaped to preserve compute allocation.');
    }
});
